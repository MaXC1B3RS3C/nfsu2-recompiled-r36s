#!/usr/bin/env python3
"""Which SPEED2.EXE a lift comes from, and the guest addresses that differ between them.

The port can be lifted from either build listed in config/exe_variants.txt. Hand-written code names
guest functions and code addresses by their v10 spelling (sub_0075BC00, NFS_VA(0x0075BC00));
config/exe_functions.txt, hooks.txt, overrides.txt and exclude.txt carry one column per exe.

  exe_variant.py detect SPEED2.EXE           print the variant id (exit 1 if unknown)
  exe_variant.py header                      regenerate src/runtime/nfs_exe_addr.h
  exe_variant.py names [--variant ID] NAME.. translate sub_<v10> names for a variant (default: the one
                                             src/recomp/gen was lifted from, else v10)
  exe_variant.py current                     print the variant src/recomp/gen was lifted from
  exe_variant.py check REF.exe TARGET.exe    re-derive the second column with exe_addr_map.py and
                                             report any row that disagrees (developer check)

run_lift.py imports detect(), va_column() and write_gen_files() from here.
"""
import hashlib, os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
CFG = os.path.join(ROOT, 'config')
GEN = os.path.join(ROOT, 'src', 'recomp', 'gen')
HEADER = os.path.join(ROOT, 'src', 'runtime', 'nfs_exe_addr.h')
TABLES = ('exe_functions.txt', 'hooks.txt', 'overrides.txt', 'exclude.txt')
VA = re.compile(r'0x[0-9A-Fa-f]{8}$')


def variants():
    out = []
    for line in open(os.path.join(CFG, 'exe_variants.txt')):
        line = line.split('#', 1)[0].split()
        if not line:
            continue
        vid, col, size, sha1, text_sha1, md5, sha256 = line[:7]
        out.append(dict(id=vid, column=int(col), size=int(size), sha1=sha1, text_sha1=text_sha1,
                        md5=md5, sha256=sha256))
    return out


def variant(vid):
    for v in variants():
        if v['id'] == vid:
            return v
    raise SystemExit(f'unknown exe variant {vid!r} (config/exe_variants.txt)')


def text_sha1(data):
    o = struct.unpack_from('<I', data, 0x3c)[0]
    so = o + 24 + struct.unpack_from('<H', data, o + 20)[0]
    _, _, _, rs, ro = struct.unpack_from('<8sIIII', data, so)
    return hashlib.sha1(data[ro:ro + rs]).hexdigest()


def detect(path):
    """Variant dict of an exe or of its normalised analysis copy (same .text), else None."""
    data = open(path, 'rb').read()
    sha1 = hashlib.sha1(data).hexdigest()
    try:
        tsha = text_sha1(data)
    except struct.error:
        tsha = None
    for v in variants():
        if sha1 == v['sha1'] or tsha == v['text_sha1']:
            return v
    return None


def rows(name):
    """[(columns[], kind, comment)] of a table; kind is '' for the lift lists."""
    out = []
    for line in open(os.path.join(CFG, name)):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        parts = line.split()
        cols = []
        while parts and VA.match(parts[0]):
            cols.append(int(parts.pop(0), 16))
        kind = parts.pop(0) if name == 'exe_functions.txt' and parts else ''
        out.append((cols, kind, ' '.join(parts)))
    return out


def va_column(name, v):
    """{va: comment} of hooks/overrides/exclude for variant v (run_lift.py)."""
    n = len(variants())
    out = {}
    for cols, _, note in rows(name):
        if len(cols) != n:
            raise SystemExit(f'config/{name}: every row needs {n} addresses: {cols}')
        out[cols[v['column'] - 1]] = note
    return out


def write_gen_files(outdir, v, exe_path):
    """Files run_lift.py adds to the generated code: the variant header and the lift marker."""
    with open(os.path.join(outdir, 'nfs_exe_variant.h'), 'w', newline='\n') as fh:
        fh.write('/* AUTO-GENERATED by run_lift.py: the SPEED2.EXE this code was lifted from. DO NOT EDIT. */\n')
        fh.write(f'#define NFS_EXE_VARIANT {v["column"]}\n#define NFS_EXE_LIFTED_ID "{v["id"]}"\n')
    # recomp_*.c: every build already globs the generated folder with that pattern
    with open(os.path.join(outdir, 'recomp_variant.c'), 'w', newline='\n') as fh:
        fh.write('/* AUTO-GENERATED by run_lift.py. DO NOT EDIT. The runtime compares this with the variant it was\n'
                 ' * built for (src/runtime/nfs_exe_addr.h) and with the SPEED2.EXE it maps. */\n')
        fh.write(f'const char nfs_exe_lifted_from[] = "{v["id"]}";\n')
        fh.write(f'const unsigned nfs_exe_lifted_size = {v["size"]}u;\n')


def current():
    p = os.path.join(GEN, 'nfs_exe_variant.h')
    if os.path.exists(p):
        m = re.search(r'NFS_EXE_LIFTED_ID "([^"]+)"', open(p).read())
        if m:
            return variant(m.group(1))
    return variant('v10')


def translate(names, v):
    table = {cols[0]: cols for cols, kind, _ in rows('exe_functions.txt') if kind == 'func'}
    out = []
    for n in names:
        m = re.match(r'sub_([0-9A-Fa-f]{8})(_orig)?$', n)
        if not m:
            raise SystemExit(f'not a sub_XXXXXXXX name: {n}')
        a = int(m.group(1), 16)
        if a not in table:
            raise SystemExit(f'{n} is not a func row of config/exe_functions.txt')
        out.append(f'sub_{table[a][v["column"] - 1]:08X}{m.group(2) or ""}')
    return out


def gen_header():
    vs = variants()
    funcs, vas, seen = [], {}, {}
    for name in TABLES:
        for cols, kind, note in rows(name):
            if len(cols) != len(vs):
                raise SystemExit(f'config/{name}: every row needs {len(vs)} addresses: {cols}')
            key = cols[0]
            if key in seen and seen[key] != cols:
                raise SystemExit(f'0x{key:08X} has different addresses in {name} and an earlier table')
            seen[key] = cols
            vas[key] = cols
            if kind == 'func':
                funcs.append(cols)
    # A renamed symbol must not be renamed again: no target may itself be a key of another row.
    keys = {c[0] for c in funcs}
    for c in funcs:
        for t in c[1:]:
            if t != c[0] and t in keys:
                raise SystemExit(f'sub_{c[0]:08X} -> sub_{t:08X} would be renamed again')
    L = ['/* GENERATED by scripts/exe_variant.py header from config/exe_variants.txt, exe_functions.txt,',
         ' * hooks.txt, overrides.txt and exclude.txt. DO NOT EDIT: edit the tables and regenerate.',
         ' *',
         ' * Hand-written code names guest code by its v10 address: sub_0075BC00, sub_0075BC00_orig and',
         ' * NFS_VA(0x0075BC00). For a lift of another SPEED2.EXE this header maps those to that exe\'s names and',
         ' * addresses. The variant comes from the lift (src/recomp/gen/nfs_exe_variant.h, written by',
         ' * run_lift.py); -DNFS_EXE_VARIANT=<n> overrides it; without either it is v10 (the original lift). */',
         '#ifndef NFS_EXE_ADDR_H', '#define NFS_EXE_ADDR_H', '']
    for v in vs:
        L.append(f'#define NFS_EXE_{v["id"].upper()} {v["column"]}')
    L += ['', '#if !defined(NFS_EXE_VARIANT) && defined(__has_include)',
          '#  if __has_include("../recomp/gen/nfs_exe_variant.h")',
          '#    include "../recomp/gen/nfs_exe_variant.h"', '#  endif', '#endif',
          '#ifndef NFS_EXE_VARIANT', f'#  define NFS_EXE_VARIANT NFS_EXE_{vs[0]["id"].upper()}', '#endif', '',
          '#define NFS_VA(x) NFS_VA_##x', '']
    for i, v in enumerate(vs):
        L.append(('#if' if i == 0 else '#elif') + f' NFS_EXE_VARIANT == NFS_EXE_{v["id"].upper()}')
        L.append(f'#define NFS_EXE_ID "{v["id"]}"')
        L.append(f'#define NFS_EXE_SIZE {v["size"]}u')
        L.append(f'#define NFS_EXE_BUILT_FOR "NFSU2_EXE_BUILT_FOR={v["id"]}:{v["size"]}"   /* read by NFSU2.sh */')
        col = v['column'] - 1
        for c in funcs:
            if c[col] != c[0]:
                L.append(f'#define sub_{c[0]:08X} sub_{c[col]:08X}')
                L.append(f'#define sub_{c[0]:08X}_orig sub_{c[col]:08X}_orig')
        for key in sorted(vas):
            L.append(f'#define NFS_VA_0x{key:08X} 0x{vas[key][col]:08X}u')
    L += ['#else', '#error "NFS_EXE_VARIANT names no exe of config/exe_variants.txt"', '#endif', '',
          '#endif /* NFS_EXE_ADDR_H */', '']
    with open(HEADER, 'w', newline='\n') as fh:
        fh.write('\n'.join(L))
    print(f'wrote {os.path.relpath(HEADER, ROOT)}: {len(funcs)} functions, {len(vas)} addresses, {len(vs)} exes')


def check(ref, tgt):
    sys.path.insert(0, HERE)
    from exe_addr_map import AddrMap
    vr, vt = detect(ref), detect(tgt)
    if not vr or not vt:
        raise SystemExit('both exes must be listed in config/exe_variants.txt')
    m = AddrMap(ref, tgt)
    bad = 0
    for name in TABLES:
        for cols, kind, note in rows(name):
            a, b = cols[vr['column'] - 1], cols[vt['column'] - 1]
            y, how, n = m.lookup(a)
            if y != b:
                bad += 1
                print(f'{name}: 0x{a:08X} -> table 0x{b:08X}, map {("0x%08X" % y) if y is not None else "?"} ({how} {n})  {note}')
    print(f'{bad} rows disagree')
    return 1 if bad else 0


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    cmd = argv[1]
    if cmd == 'detect' and len(argv) == 3:
        v = detect(argv[2])
        if not v:
            print('unknown'); return 1
        print(v['id']); return 0
    if cmd == 'header':
        gen_header(); return 0
    if cmd == 'current':
        print(current()['id']); return 0
    if cmd == 'names':
        args = argv[2:]
        v = current()
        if args[:1] == ['--variant']:
            v = variant(args[1]); args = args[2:]
        print(' '.join(translate(args, v))); return 0
    if cmd == 'check' and len(argv) == 4:
        return check(argv[2], argv[3])
    raise SystemExit(__doc__)


if __name__ == '__main__':
    sys.exit(main(sys.argv))
